"""Tiny test programs over the supplied project's header, exercising its serial hook model."""
from pathlib import Path
import sys
project=Path(sys.argv[1]).read_bytes()
out=Path(sys.argv[2])
for name,value,sc in [('host',0x44,0x81),('guest',0x77,0x80)]:
    rom=bytearray(32768);rom[0x100:0x150]=project[0x100:0x150];rom[0x100:0x103]=bytes([0xc3,0x50,0x01])
    rom[0x147:0x14a]=bytes([0,0,0])
    # Serial ISR: read SB; hook substitutes the wire byte; store it; rearm transfer; return.
    code=[0xf0,0x01,0xfe,0xff,0x28,0x03,0xea,0x01,0xc0,0x3e,sc,0xe0,0x02,0xd9]
    rom[0x58:0x58+len(code)]=bytes(code)
    # Boot, own outgoing byte, serial IE, initial transfer, HALT loop.
    code=[0xf3,0x31,0xfe,0xdf,0x3e,value,0xea,0x00,0xc0,0xaf,0xe0,0x0f,
          0x3e,0x08,0xe0,0xff,0x3e,value,0xe0,0x01,0x3e,sc,0xe0,0x02,0xfb,0x76,0x18,0xfd]
    rom[0x150:0x150+len(code)]=bytes(code)
    checksum=0
    for v in rom[0x134:0x14d]:checksum=(checksum-v-1)&255
    rom[0x14d]=checksum;total=sum(rom[:0x14e])+sum(rom[0x150:]);rom[0x14e:0x150]=bytes([total>>8&255,total&255])
    (out/f'{name}.gbc').write_bytes(rom)
